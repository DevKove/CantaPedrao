  const normalize = value => value.replace(/\s+/g, " ").trim();
  const translate = value => {
    const clean = normalize(value);
    if (!clean || clean.length > 240) return value;
    if (translations.has(clean)) {
      const leading = value.match(/^\s*/)?.[0] || "";
      const trailing = value.match(/\s*$/)?.[0] || "";
      return leading + translations.get(clean) + trailing;
    }
    return value;
  };

  function translateElement(element) {
    if (!(element instanceof Element)) return;
    if (element.matches("script,style,code,pre,textarea")) return;
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      const parent = node.parentElement;
      if (!parent || parent.closest("script,style,code,pre,textarea")) continue;
      const next = translate(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    for (const attr of ["placeholder", "title", "aria-label", "alt"]) {
      if (element.hasAttribute(attr)) {
        const value = element.getAttribute(attr);
        const next = translate(value);
        if (next !== value) element.setAttribute(attr, next);
      }
    }
    if (element instanceof HTMLInputElement && ["button", "submit", "reset"].includes(element.type)) {
      const next = translate(element.value);
      if (next !== element.value) element.value = next;
    }
  }

  function start() {
    document.documentElement.lang = "pt-BR";
    translateElement(document.body);
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === "characterData") {
          const next = translate(record.target.nodeValue);
          if (next !== record.target.nodeValue) record.target.nodeValue = next;
        }
        for (const node of record.addedNodes || []) {
          if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
          else if (node.nodeType === Node.TEXT_NODE) {
            const next = translate(node.nodeValue);
            if (next !== node.nodeValue) node.nodeValue = next;
          }
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start, { once: true });
  } else {
    start();
  }
